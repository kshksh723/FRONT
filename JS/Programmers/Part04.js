// 산술 연산자
// 연산자(+,-,*,/,%)는 피연산자를 두 개 갖고 있는 이항 연산자이다

// A + B에서 피연산자는 A와 B이다
/*
피연산자를 하나만 갖고 있는 단항 연산자도 있다 +와 -가 대표적이다
변수 a가 있을 때 -a는 해당 값의 음수를 반환한다

변수에 사용할 수 있는 증감연산자 
    변수의 값을 증가시키는 연산자인 ++와 변수의 값을 감소시키는 연산자인 --가 있다
    두 연산자는 변수의 값을 수식 안에서 사용할 수 있을 뿐만 아니라 변수의 값을 갱신할 수도 있다

    🧩 자바스크립트의 Math 객체 => 자바스크립트에서 수학과 관련된 여러 상수 및 함수가 Math 객체에 정의되어 있다


    [대표적인 함수]
    ✔️ Math.pow(A,B); : A의 B승을 구한다
    ✔️ Math.sqrt(A); : sqrt는 제곱근(square root)의 약자로 A의 제곱근을 구한다 
    ✔️ Math.random(); 괄호 안에 아무런 값을 넣지 않으면 0~1 사이의 난수를 발생시킨다. 여기에서 난수는 특정한 배열 순서나 규칙이 없는 
                        무작위 숫자를 뜻한다
*/
Math.pow(2, 3);
// 8 --> 2의 3승인 8
Math.sqrt(16);
// 4 --> 16의 제곱근인 4
Math.random();
// 0.1158l...... -> 생성된 0~1 사이의 난수

// 특히 Math.random() 함수를 이용하면 프로그램에서 다양한 무작위 효과를 낼 수 있다

