// 아무것도 실행되지 않고 undefine가 출력된다 --> 이것은 반환값이 없다는 뜻이단

/*
[정리]
- 호출하여 여러 번 실행할 수 있는 코드 블록을 함수
- 함수를 사용하면 반복되는 코드를 줄일 수 있어 프로그램을 개발하거나 수정하기가 수월
- 함수를 정의할 때

function 함수이름(매개변수 1, 매개변수 2){
    실행할 코드
    return 결과값;
}

- return 구문에는 함수의 출력으로 내보낼 값을 입력하는데 이를 반환값이라고 한다
- return 구문을 만나면 함수는 즉시 종료된다
- 함수를 호출할 때는 '함수 이름(인수1, 인수2)의 형태로 호출한다

*/

