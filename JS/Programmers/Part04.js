/*
⚡ 이항 연산자는 피연산자가 두 개 (A,B)인 연산자로 'A 연산자 B'의 꼴로 사용한다 종류에는 +,-,*,/,%가 있다
⚡ 단항 여난자는 피연산자가 하나인 연산자(A)로 '연산자A'또는 'A연산자' 꼴로 사용한다 종류에는 ++, --가 있다
*/

/*
[함수를 정의하는 방법]
function 함수이름(매개변수 1, 매개변수 2){
        실행할 코드
        return 결괏값;
}


*/
